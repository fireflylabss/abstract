mod en;
mod pt;
use en::en;
use pt::pt;

pub fn lookup(lang: Lang, key: Key) -> &'static str {
    match lang {
        Lang::En => en(key),
        Lang::PtBr => pt(key),
    }
}

pub fn t(key: Key) -> &'static str {
    lookup(current(), key)
}

pub fn tf(key: Key, args: &[(&str, &str)]) -> String {
    let mut value = t(key).replace("{MOD}", super::prefs::MOD);
    for (name, replacement) in args {
        value = value.replace(&format!("{{{name}}}"), replacement);
    }
    value
}

